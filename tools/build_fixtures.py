def build_menu():
    items = []
    for line in MENU_RAW.strip().splitlines():
        line = line.strip()
        if not line:
            continue
        parts = line.split("|")
        while len(parts) < 9:
            parts.append("")
        code, name, price, orig, role, protein, spicy, cat, compose = parts[:9]
        items.append({
            "code": code, "name": name,
            "price": float(price), "origPrice": float(orig),
            "role": role, "protein": protein, "spicy": bool(int(spicy)),
            "category": cat,
            "compose": [c for c in compose.split(";") if c],
        })
    return items


def build_nutrition():
    table = {}
    for line in NUTRITION_RAW.strip().splitlines():
        line = line.strip()
        if not line:
            continue
        f = line.split(",")
        if len(f) < 9:
            continue
        table[f[0]] = {
            "energyKcal": float(f[3]), "protein": float(f[4]), "fat": float(f[5]),
            "carbohydrate": float(f[6]), "sodium": float(f[7]), "calcium": float(f[8]),
        }
    return table


